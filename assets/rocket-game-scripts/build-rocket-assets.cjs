const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = __dirname;
const directory = '../rocket-game-assets';
function scan(folder) {
  return fs.readdirSync(path.join(root, folder), { withFileTypes: true }).flatMap(entry => {
    const file = `${folder}/${entry.name}`;
    if (entry.isDirectory()) return scan(file);
    if (!/\.(webp|png|jpe?g|gif|svg|mp4|webm|mp3|wav|ogg|m4a|aac|woff2?|ttf|otf)$/i.test(file) || /reference|[- ]old\./i.test(file)) return [];
    const data = fs.readFileSync(path.join(root, file));
    return [{ url: file, bytes: data.length, revision: crypto.createHash('sha256').update(data).digest('hex').slice(0, 16) }];
  });
}
const entries = scan(directory).sort((a, b) => a.url.localeCompare(b.url));
fs.writeFileSync(path.join(root, 'rocket-game-assets.js'), `/* Generated by npm run assets:rocket. Do not edit. */\nself.ROCKET_ASSETS = ${JSON.stringify(entries, null, 2)};\n`);
const manifestRevision = crypto.createHash('sha256').update(JSON.stringify(entries)).digest('hex').slice(0, 16);
for (const name of ['rocket-game.html', 'sw.js']) {
  const file = path.join(root, name);
  fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace(/rocket-game-assets\.js\?v=[\w]+/g, `rocket-game-assets.js?v=${manifestRevision}`));
}
console.log(`Rocket assets: ${entries.length} files, ${(entries.reduce((n, a) => n + a.bytes, 0) / 1048576).toFixed(1)} MB`);
