const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const scripts = __dirname, media = path.resolve(scripts, '../my-carz-game-assets');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 16);
function walk(folder) {
  return fs.readdirSync(folder, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(folder, entry.name);
    return entry.isDirectory() ? walk(file) : [file];
  });
}
const entries = walk(media).filter(file => /\.(webp|png|gif|svg|otf|ttf|mp3|wav|mp4|webm)$/i.test(file) &&
  !/reference|referene|[/\\]old-/i.test(file)).sort().map(file => {
  const bytes = fs.readFileSync(file);
  return { url: '../my-carz-game-assets/' + path.relative(media, file).split(path.sep).join('/'), bytes: bytes.length, revision: hash(bytes) };
});
const content = `/* Generated by build-my-carz-assets.cjs. */\nconst CARZ_ASSETS = ${JSON.stringify(entries, null, 2)};\n`;
fs.writeFileSync(path.join(scripts, 'my-carz-assets.js'), content);
const revision = hash(content);
for (const name of ['my-carz.html', 'sw.js']) {
  const filename = path.join(scripts, name);
  if (fs.existsSync(filename)) fs.writeFileSync(filename, fs.readFileSync(filename, 'utf8').replace(/my-carz-assets\.js\?v=[a-z0-9]+/g, `my-carz-assets.js?v=${revision}`));
}
console.log(`My Carz manifest: ${entries.length} files, ${(entries.reduce((sum, entry) => sum + entry.bytes, 0) / 1048576).toFixed(1)} MB`);
