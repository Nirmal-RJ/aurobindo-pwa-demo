const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../solvent-master-game-assets');
const entries = [];
// The user explicitly approved these four reference images as temporary demo slides.
const temporaryDemos = /^demo-page-2-[a-d]-reference\.webp$/;
function visit(directory) {
  for (const item of fs.readdirSync(directory, { withFileTypes: true }).sort((a,b) => a.name.localeCompare(b.name))) {
    const file = path.join(directory, item.name);
    if (/(?:^|[-_ ])(?:reference|old)(?:[-_. ]|$)/i.test(item.name) && !(path.basename(directory) === 'page-2-demo-page' && temporaryDemos.test(item.name))) continue;
    if (item.isDirectory()) visit(file);
    else if (/\.(?:webp|png|jpg|jpeg|svg|gif|mp3|wav|aac|mp4|webm|woff2?|ttf|otf)$/i.test(item.name)) {
      const bytes = fs.readFileSync(file);
      entries.push({ url: '../solvent-master-game-assets/' + path.relative(root, file).split(path.sep).map(encodeURIComponent).join('/'), bytes: bytes.length, revision: crypto.createHash('sha256').update(bytes).digest('hex') });
    }
  }
}
visit(root);
fs.writeFileSync(path.join(__dirname, 'solvent-master-assets.js'), '// Generated by build-solvent-master-assets.cjs. Do not edit.\nglobalThis.SOLVENT_MASTER_ASSETS = ' + JSON.stringify(entries, null, 2) + ';\n');
console.log(`Solvent Master: ${entries.length} production assets, ${entries.reduce((sum,e)=>sum+e.bytes,0)} bytes`);
